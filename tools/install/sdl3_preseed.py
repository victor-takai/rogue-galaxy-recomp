#!/usr/bin/env python3
"""Record SDL3's configure answers for the toolchain a build was configured with.

Writes thirdparty/dq8-gfx/cmake/sdl3-preseed.cmake from BUILD_DIR's CMake
cache (default build/game): the check answers SDL3 added to it
(DQ8_SDL3_ANSWER_NAMES) and the key they hold for (DQ8_SDL3_PRESEED_KEY: the
SDL release and patches, compiler and target, CMake, flags, headers).
Dq8Sdl3Preseed.cmake loads them at configure when the key matches.

Run it after changing the installer's toolchain (the build container, install.sh),
SDL3's release (thirdparty/dq8-gfx/CMakeLists.txt) or its patches
(thirdparty/dq8-gfx/cmake/patches), on a fresh folder configured with that
toolchain and -DDQ8_SDL3_PRESEED=OFF, e.g.

  cmake -S . -B build/sdl3-answers -G Ninja -DCMAKE_BUILD_TYPE=Release \\
        -DCMAKE_C_COMPILER=clang -DCMAKE_CXX_COMPILER=clang++ -DDQ8_SDL3_PRESEED=OFF
  python tools/install/sdl3_preseed.py build/sdl3-answers

It refuses a folder whose answers are not SDL3's own for today's key.
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "thirdparty" / "dq8-gfx" / "cmake" / "sdl3-preseed.cmake"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("build", nargs="?", type=Path, default=ROOT / "build" / "game")
    args = parser.parse_args()
    path = args.build / "CMakeCache.txt"
    if not path.is_file():
        parser.error(f"{path} not found: configure the folder first")
    cache = {}
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        m = re.match(r"^([A-Za-z0-9_]+):([A-Z]+)=(.*)$", line)
        if m:
            cache[m.group(1)] = m.group(3)
    key = cache.get("DQ8_SDL3_PRESEED_KEY")
    if key is None:
        parser.error(f"{path} has no DQ8_SDL3_PRESEED_KEY: not a build with the SDL3 GPU backend")
    seed = cache.get("DQ8_SDL3_PRESEED", "ON").upper()
    if not (seed in ("OFF", "0", "FALSE", "NO", "N", "IGNORE", "NOTFOUND", "") or seed.endswith("-NOTFOUND")):
        parser.error(f"{args.build} was not configured with -DDQ8_SDL3_PRESEED=OFF: configure a fresh "
                     "folder with it, so that SDL3 checks everything and the key covers the headers")
    if cache.get("DQ8_SDL3_CHECKED_FOR") != key:
        parser.error(f"SDL3's answers in {args.build} were not checked with today's toolchain and SDL "
                     "release (or the folder is older than this check): configure a fresh folder")
    if cache.get("DQ8_SDL3_PRESEEDED") == "ON":
        parser.error(f"{args.build} was given recorded answers: configure a fresh folder "
                     "with -DDQ8_SDL3_PRESEED=OFF, so that the answers are SDL3's own")
    names = [n for n in cache.get("DQ8_SDL3_ANSWER_NAMES", "").split(";") if n]
    if len(names) < 100:
        parser.error(f"only {len(names)} SDL3 answers recorded in {path}: configure a fresh folder")
    answers = {}
    for name in names:
        value = cache.get(name)
        if value not in ("1", ""):
            parser.error(f"{name}={value!r}: not a check answer this file can hold")
        answers[name] = value
    if re.search(r'["\\$;]', key):
        parser.error(f"the key {key!r} holds a character this file cannot hold")
    lines = [
        "# Generated by tools/install/sdl3_preseed.py; do not edit. SDL3's configure",
        "# checks as answered with the toolchain below (cmake/Dq8Sdl3Preseed.cmake).",
        f'set(DQ8_SDL3_PRESEED_FOR "{key}")',
        "set(DQ8_SDL3_PRESEED_ANSWERS",
        *(f'    "{name}={value}"' for name, value in sorted(answers.items())),
        ")",
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(ROOT)}: {len(answers)} answers for {key}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
