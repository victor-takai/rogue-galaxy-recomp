# Characters drawn into a glyph of their own, not the one the table uses
# today (the x stands in for the multiplication sign there).
GLYPH_FOR = {"×": "multiply"}


def parse(spec: str):
    toks = spec.split()
    if toks[0] == "part":  # "part GLYPH:CONTOUR x,y size,width [uniform]": Andika's own contour
        uniform = toks[-1] == "uniform"  # sized only, never narrowed nor widened
        name, index = toks[1].split(":")
        nodes = [tuple(float(v) for v in tk.split(",")) + ("s",) for tk in toks[2:len(toks) - uniform]]
        return {"nodes": nodes, "closed": True, "round": False, "fill": True, "shape": "part",
                "part": (name, int(index)), "uniform": uniform}
    if toks[0] in ("dot", "comma"):
        nodes = [tuple(float(v) for v in t.split(",")) + ("s",) for t in toks[1:]]
        return {"nodes": nodes, "closed": True, "round": False, "fill": True, "shape": toks[0]}
    flags = set()
    while toks and toks[-1] in ("z", "r", "f"):
        flags.add(toks.pop())
    closed = "z" in flags or "f" in flags
    nodes = []
    for i, t in enumerate(toks):
        kind = None
        if t[-1] in "cshtu":
            kind, t = t[-1], t[:-1]
        x, y = (float(v) for v in t.split(","))
        if kind is None:
            kind = "s" if (closed or 0 < i < len(toks) - 1) else "c"
        nodes.append((x, y, kind))
    return {"nodes": nodes, "closed": closed, "round": "r" in flags, "fill": "f" in flags, "shape": None}
